      def('P', "####. #...# #...# ####. #.... #.... #....");
      def('Q', ".###. #...# #...# #...# #.#.# #..#. .##.#");
      def('R', "####. #...# #...# ####. #.#.. #..#. #...#");
      def('S', ".#### #.... #.... .###. ....# ....# ####.");
